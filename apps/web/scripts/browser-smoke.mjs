import {chromium} from 'playwright';
import fs from 'node:fs';
const out='../../docs/implementation/evidence';fs.mkdirSync(out,{recursive:true});
const browser=await chromium.launch({headless:true,executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',args:['--disable-background-networking','--disable-extensions','--disable-sync','--renderer-process-limit=2']});
const page=await browser.newPage({viewport:{width:1365,height:900}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:3000',{waitUntil:'networkidle'});
await page.screenshot({path:out+'/home-desktop.png',fullPage:true});
console.log('homepage',await page.title(),'cards',await page.locator('.vehicle-card').count());
await page.setViewportSize({width:390,height:844});await page.screenshot({path:out+'/home-mobile.png',fullPage:true});
console.log('mobile overflow',await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth));
await page.goto('http://127.0.0.1:3000/sign-in',{waitUntil:'networkidle'});
await page.getByLabel('Email address',{exact:true}).fill('seller@example.test');
await page.getByLabel('Password',{exact:true}).fill('Development-only-2026!');
await page.getByRole('button',{name:'Sign in',exact:true}).click();
await page.waitForURL('**/account');await page.getByRole('heading',{name:'Seller dashboard',exact:true}).waitFor();
await page.screenshot({path:out+'/seller-mobile.png',fullPage:true});
console.log('seller dashboard',await page.locator('tbody tr').count());
fs.writeFileSync(out+'/browser-smoke.json',JSON.stringify({errors,homepage:true,mobile_overflow:await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),seller_login:true},null,2));
await browser.close();if(errors.length)process.exitCode=1;
